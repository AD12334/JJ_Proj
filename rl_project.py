class DQN:
    def __init__(
        self,
        env,
        height,
        width,
        channels,
        action_size,
        epochs,
        epsilon,
        epsilon_decay,
        epsilon_min,
        threshold,
        alpha,
        alpha_decay,
        gamma,
        seed=42,
    ):
        self.env = env
        self.action_size = action_size
        self.epochs = epochs
        self.epsilon = epsilon
        self.epsilon_decay = epsilon_decay
        self.epsilon_min = epsilon_min
        self.threshold = threshold
        self.memory = deque(maxlen=500_000)
        self.gamma = gamma
        self.model = self.build_model(
            height, width, channels, action_size, alpha, alpha_decay, seed
        )
        self.model_target = self.build_target_model()

    def build_model(self, height, width, channels, action_size, alpha, alpha_decay, seed):
        tf.random.set_seed(seed)  # extra code – ensures reproducibility on the CPU
        # input = (84,84,3)

        model = tf.keras.Sequential([
            layers.Input(shape=(height, width, channels)),
            layers.Conv2D(32, kernel_size=8, strides=4, activation='elu', padding='valid'),
            layers.Conv2D(64, kernel_size=4, strides=2, activation='elu', padding='valid'),
            #layers.MaxPooling2D(),
            layers.Conv2D(64, kernel_size=3, strides=1, activation='elu', padding='valid'),
            #layers.MaxPooling2D(),
            layers.Flatten(),
            layers.Dense(256, activation="elu"),
            layers.Dense(action_size, activation='linear')
        ])

        lr_schedule = optimizers.schedules.InverseTimeDecay(
            initial_learning_rate=alpha, decay_steps=1, decay_rate=alpha_decay
        )
        model.compile(loss=tf.keras.losses.Huber(), optimizer=optimizers.Adam(learning_rate=lr_schedule))

        return model

    def build_target_model(self):
        target = models.clone_model(self.model)
        target.set_weights(self.model.get_weights())
        return target

    def choose_action(self, state, epsilon=None): #epsilon is the probability of exploring a random action
        if epsilon is None:
            epsilon = self.epsilon
        if np.random.rand() < epsilon:
            return np.random.randint(self.action_size)  # random action
        else:
            Q_values = self.model(state, training=False)[0].numpy()
            return Q_values.argmax()  # optimal action according to the DQN

    def replay(self, batch_size, memory):
        if len(memory) < batch_size:
            return
        minibatch = random.sample(memory, batch_size)
        states = np.concatenate([s for s, _, _, _, _ in minibatch])
        next_states = np.concatenate([n for _, _, _, n, _ in minibatch])
        q = self.model.predict(states, verbose=0)
        q_next = self.model_target.predict(next_states, verbose=0)
        for j, (_, action, reward, _, done) in enumerate(minibatch):
            q[j][action] = reward if done else reward + self.gamma * np.max(q_next[j])
        # backpropagation
        self.model.fit(states, q, verbose=0)

    def remember(self, state, action, reward, next_state, done):
        return self.memory.append((state, action, reward, next_state, done))

    def train(self):
        scores = deque(maxlen=100)
        avg_scores = []
        step = 0
        for e in range(self.epochs):
            obs, info = self.env.reset()
            state = preprocess_state(obs)
            state = combine_images(state, state)
            done = False
            i = 0
            while not done:
                action = self.choose_action(state)
                next_state, reward, terminated, truncated, info = self.env.step(action)
                done = (terminated or truncated)
                next_state = preprocess_state(next_state)
                next_state = combine_images(state, next_state)
                #print(next_state.shape)
                # storing terminated instead of done is slightly more correct
                # we changes reward to np.sign(reward) so it only remembers  the sign instead of the value
                self.remember(state, action, np.sign(reward), next_state, done)
                state = next_state
                self.epsilon = max(self.epsilon_min, self.epsilon_decay * self.epsilon)
                i += reward
                step += 1
                if step > 50000 and step % 4 == 0:
                    self.replay(32, self.memory)
                if step % 10000 == 0:
                    self.model_target.set_weights(self.model.get_weights())

            #while loop finished
            print(f'Steps completed before termination {step} - epsilon: {self.epsilon} - reward {i}')
            scores.append(i)
            mean_score = np.mean(scores)
            avg_scores.append(mean_score)
            if mean_score >= self.threshold:
                print('Solved after {} trials '.format(e))
                return avg_scores
            if e % 5 == 0:
                print('[Epoch {}] - Average Score: {} - epsilon: {}.'.format(e,mean_score,self.epsilon))

        return avg_scores

