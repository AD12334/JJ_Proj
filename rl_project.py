class DQN:
    def __init__(
        self,
        env,
        height,
        width,
        channels,
        action_size,
        epochs,
        epsilon,
        epsilon_decay,
        epsilon_min,
        threshold,
        alpha,
        alpha_decay,
        gamma,
        seed=42,
    ):
        self.env = env
        self.action_size = action_size
        self.epochs = epochs
        self.epsilon = epsilon
        self.epsilon_decay = epsilon_decay
        self.epsilon_min = epsilon_min
        self.threshold = threshold
        self.memory = deque(maxlen=100_000)  # ~5.6 GB with uint8 frame stacks
        self.gamma = gamma
        self.model = self.build_model(
            height, width, channels, action_size, alpha, alpha_decay, seed
        )
        self.model_target = self.build_target_model()

    def build_model(self, height, width, channels, action_size, alpha, alpha_decay, seed):
        tf.random.set_seed(seed)  # extra code – ensures reproducibility on the CPU
        # input = (84,84,3)

        model = tf.keras.Sequential([
            layers.Input(shape=(height, width, channels)),
            layers.Conv2D(32, kernel_size=8, strides=4, activation='elu', padding='valid'),
            layers.Conv2D(64, kernel_size=4, strides=2, activation='elu', padding='valid'),
            #layers.MaxPooling2D(),
            layers.Conv2D(64, kernel_size=3, strides=1, activation='elu', padding='valid'),
            #layers.MaxPooling2D(),
            layers.Flatten(),
            layers.Dense(256, activation="elu"),
            layers.Dense(action_size, activation='linear')
        ])

        lr_schedule = optimizers.schedules.InverseTimeDecay(
            initial_learning_rate=alpha, decay_steps=1, decay_rate=alpha_decay
        )
        model.compile(loss=tf.keras.losses.Huber(), optimizer=optimizers.Adam(learning_rate=lr_schedule))

        return model

    def build_target_model(self):
        target = models.clone_model(self.model)
        target.set_weights(self.model.get_weights())
        return target

    def choose_action(self, state, epsilon=None): #epsilon is the probability of exploring a random action
        if epsilon is None:
            epsilon = self.epsilon
        if np.random.rand() < epsilon:
            return np.random.randint(self.action_size)  # random action
        else:
            Q_values = self.model(state, training=False)[0].numpy()
            return Q_values.argmax()  # optimal action according to the DQN

    def replay(self, batch_size, memory):
        if len(memory) < batch_size:
            return
        minibatch = random.sample(memory, batch_size)
        # frames are stored as uint8, convert back to float32 in [0, 1]
        states = np.concatenate([m[0] for m in minibatch]).astype(np.float32) / 255
        actions = np.array([m[1] for m in minibatch])
        rewards = np.array([m[2] for m in minibatch], dtype=np.float32)
        next_states = np.concatenate([m[3] for m in minibatch]).astype(np.float32) / 255
        dones = np.array([m[4] for m in minibatch], dtype=np.float32)
        # direct model calls avoid the heavy per-call overhead of predict()/fit()
        q = self.model(states, training=False).numpy()
        q_next = self.model_target(next_states, training=False).numpy()
        q[np.arange(batch_size), actions] = rewards + (1 - dones) * self.gamma * q_next.max(axis=1)
        # backpropagation
        loss = self.model.train_on_batch(states, q)
        return float(loss)

    @staticmethod
    def to_uint8(state):
        return np.round(np.asarray(state) * 255).astype(np.uint8)

    def remember(self, state, action, reward, next_state, done):
        # store as uint8 numpy arrays (4x smaller than float32, and kept in CPU RAM not GPU memory)
        return self.memory.append(
            (self.to_uint8(state), action, reward, self.to_uint8(next_state), done)
        )

    def train(self):
        scores = deque(maxlen=100)
        avg_scores = []
        step = 0
        best_mean = -np.inf
        csv_file = open(f"{RUN_DIR}/episodes.csv", "w", newline="")
        writer = csv.writer(csv_file)
        writer.writerow(["episode", "total_steps", "episode_steps", "reward",
                        "mean_100", "epsilon", "mean_loss"])
        for e in range(self.epochs):
            obs, info = self.env.reset()
            state = combine_images(obs, obs)
            done = False
            i = 0
            losses, ep_steps = [], 0
            while not done:
                action = self.choose_action(state)
                next_state, reward, terminated, truncated, info = self.env.step(action)
                done = (terminated or truncated)
                next_state = combine_images(state, next_state)
                #print(next_state.shape)
                # storing terminated instead of done is slightly more correct
                # we changes reward to np.sign(reward) so it only remembers  the sign instead of the value
                self.remember(state, action, np.sign(reward), next_state, done)
                state = next_state
                self.epsilon = max(self.epsilon_min, self.epsilon_decay * self.epsilon)
                i += reward
                step += 1
                ep_steps += 1
                if step > 50000 and step % 4 == 0:
                    loss = self.replay(32, self.memory)
                    if loss is not None:
                        losses.append(loss)
                if step % 10000 == 0:
                    self.model_target.set_weights(self.model.get_weights())

            #while loop finished
            print(f'Steps completed before termination {step} - epsilon: {self.epsilon} - reward {i}')
            scores.append(i)
            mean_score = np.mean(scores)
            avg_scores.append(mean_score)
            mean_loss = np.mean(losses) if losses else ""
            writer.writerow([e, step, ep_steps, i, mean_score, self.epsilon, mean_loss])
            csv_file.flush()                       # so the file is up to date if the run crashes
            log.info(f"ep {e}  steps {step}  reward {i:.0f}  mean100 {mean_score:.1f}  "
                    f"eps {self.epsilon:.3f}  loss {mean_loss}")
            if e % 50 == 0:
                self.model.save(f"{RUN_DIR}/checkpoints/ep{e}.keras") # save our model
            if mean_score > best_mean and step > 50000:
                best_mean = mean_score
                self.model.save(f"{RUN_DIR}/best.keras")
                
            if len(scores) == scores.maxlen and mean_score >= self.threshold:
                print('Solved after {} trials '.format(e))
                break
            if e % 5 == 0:
                print('[Epoch {}] - Average Score: {} - epsilon: {}.'.format(e,mean_score,self.epsilon))
                
        csv_file.close()
        self.model.save(f"{RUN_DIR}/final.keras")
        with open(f"{RUN_DIR}/history.pkl", "wb") as f:
            pickle.dump({"avg_scores": avg_scores}, f) #write results to file
        return avg_scores

