def combine_images(img1, img2, m=4):
    img1, img2 = np.squeeze(img1), np.squeeze(img2)
    if img1.ndim == 3 and img1.shape[2] == m:                     # existing stack (H, W, m)
        im = np.append(img1[:, :, 1:], img2[:, :, None], axis=2)  # drop oldest, add newest
    else:                                                         # first frame (H, W)
        im = np.stack([img1] * m, axis=2)
    return tf.expand_dims(im, 0)                                  # (1, H, W, m)

